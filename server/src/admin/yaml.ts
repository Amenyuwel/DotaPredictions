import type { RunMeta, Scoring } from "../validate.js"

/**
 * The effective scoring table, as `engine/config/<tournament>/scoring.yaml`.
 *
 * This exists because of a trap the overlay feature would otherwise set. An
 * overlay is a correction applied between crawls. It stays on top of whatever
 * run is current -- so once a later crawl publishes a run that already carries
 * the correction, the overlay is a no-op that nobody notices. Until the day
 * somebody publishes a run where that value is deliberately DIFFERENT, and the
 * forgotten overlay quietly puts the old number back.
 *
 * The way out is to make the round trip easy: an admin who fixes a number here
 * should be able to see, in one click, exactly what to write into the config the
 * engine reads. Then `redundantEntries` tells them when the correction has
 * landed and the overlay entry can be dropped.
 *
 * Emitted by hand rather than through a YAML library. The shape is fixed and
 * tiny -- nested maps of numbers, booleans, short strings and string lists --
 * and the output has to be readable enough to paste beside the comments already
 * in that file. A dependency that serialises arbitrary graphs earns nothing
 * against that, and would reformat the whole document rather than the part that
 * changed.
 */
export function toScoringYaml(scoring: Scoring, run: RunMeta): string {
  const lines: string[] = []

  lines.push(
    "# Generated by the configuration editor from the overlay in force.",
    `# Tournament ${run.tournamentId}, stage ${run.stage}, run ${run.runId}.`,
    "#",
    "# This is what the tool is CURRENTLY scoring with. It is not yet what the",
    "# engine reads: an overlay lives in the database and applies on top of",
    "# whatever run is published, so until these values are written into this",
    "# file the next crawl will publish a run without them and the overlay will",
    "# go on silently patching it.",
    "#",
    "# Paste the blocks below into engine/config/" + run.tournamentId + "/scoring.yaml,",
    "# keeping the comments already there -- they explain traps this file cannot.",
    "# Then re-run publish.py and drop the overlay entries the editor marks as",
    "# matching the published run.",
    "",
  )

  lines.push(`version: ${quote(scoring.version)}`)
  lines.push(`verified_against_client: ${scoring.verifiedAgainstClient}`)
  lines.push("")

  lines.push("stats:")
  const unmeasurable: string[] = []
  for (const key of Object.keys(scoring.stats).sort()) {
    const spec = scoring.stats[key]!
    const fields = [`per_unit: ${num(spec.perUnit)}`, `color: ${spec.color}`]
    if (spec.base !== 0) fields.push(`base: ${num(spec.base)}`)
    lines.push(`  ${key}: {${fields.join(", ")}}`)
    if (!spec.measurable) unmeasurable.push(key)
  }
  lines.push("")

  lines.push(
    "# Excluded from emblem choice rather than scored as zero, so the model never",
    "# recommends an emblem it cannot value.",
  )
  if (unmeasurable.length === 0) {
    lines.push("unmeasurable: []")
  } else {
    lines.push("unmeasurable:")
    for (const key of unmeasurable) lines.push(`  - ${key}`)
  }
  lines.push("")

  lines.push("emblem_quality:")
  for (const [tier, bonus] of Object.entries(scoring.quality)) {
    lines.push(`  ${tier}: ${num(bonus)}`)
  }
  lines.push("")

  lines.push(
    "# `condition_rule` names the implemented rule that gates the trait's own",
    "# bonus, and it is required: a trait without one pays unconditionally.",
  )
  lines.push("emblem_traits:")
  for (const [name, spec] of Object.entries(scoring.traits)) {
    const fields = [`bonus: ${num(spec.bonus)}`]
    if (spec.adjacentBonus !== 0) fields.push(`adjacent_bonus: ${num(spec.adjacentBonus)}`)
    fields.push(`condition_rule: ${spec.conditionRule ?? "always"}`)
    if (spec.condition) fields.push(`condition: ${quote(spec.condition)}`)
    lines.push(`  ${name}: {${fields.join(", ")}}`)
  }
  lines.push("")

  lines.push(`banner_colors: [${scoring.colors.join(", ")}]`)
  lines.push("")

  if (scoring.bannerColors) {
    lines.push(
      "# The colour of each SLOT, fixed by role. Not a preference and not",
      "# one-of-each: this rule decides which stats a slot can hold at all.",
      "banner_slot_colors:",
    )
    for (const [role, row] of Object.entries(scoring.bannerColors)) {
      lines.push(`  ${role}: [${row.join(", ")}]`)
    }
    lines.push("")
  }

  lines.push(
    "# The coach block is NOT reproduced here. It is not overlayable -- its",
    "# probabilities are measured against a specific roster by the engine, not",
    "# typed in -- so the copy already in scoring.yaml is the only one and must",
    "# be left exactly as it is.",
  )

  return lines.join("\n") + "\n"
}

/** A number as YAML, keeping a trailing `.0` off integers and full precision on
 * everything else. `1e-7` would round-trip through YAML as a string in some
 * parsers, so exponent notation is expanded. */
function num(value: number): string {
  if (Number.isInteger(value)) return String(value)
  const plain = value.toFixed(10).replace(/0+$/, "").replace(/\.$/, "")
  return plain.includes("e") || plain.includes("E") ? value.toFixed(10) : plain
}

/** Double-quoted, with the two characters that would end the string early
 * escaped. Everything emitted here is a short identifier or a sentence of
 * prose, so this is the whole escape set that can occur. */
function quote(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`
}
